/**
 * 食材名からカテゴリをキーワード一致で推測する。
 * どれにも当てはまらない場合は「その他」を返す。
 */
export function inferCategory(name) {
  if (!name) return "その他";
  for (const rule of RULES) {
    if (rule.keywords.some((k) => name.includes(k))) {
      return rule.category;
    }
  }
  return "その他";
}
